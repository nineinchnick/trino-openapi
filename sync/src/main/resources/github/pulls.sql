-- Pull requests. The endpoint has no parameter to read only recently updated ones, but it can sort them,
-- so read pages of the most recently updated ones, until a page has no changes.
CREATE SCHEMA IF NOT EXISTS ${target};

CREATE TABLE IF NOT EXISTS ${target}.pulls AS
SELECT
    owner,
    repo,
    id,
    node_id,
    url,
    html_url,
    number,
    state,
    locked,
    title,
    user.id AS user_id,
    user.login AS user_login,
    body,
    transform(labels, label -> label.name) AS label_names,
    milestone.id AS milestone_id,
    milestone.title AS milestone_title,
    active_lock_reason,
    created_at,
    updated_at,
    closed_at,
    merged_at,
    merge_commit_sha,
    assignee.id AS assignee_id,
    assignee.login AS assignee_login,
    transform(assignees, assignee -> assignee.login) AS assignee_logins,
    transform(requested_reviewers, reviewer -> reviewer.login) AS requested_reviewer_logins,
    head.ref AS head_ref,
    head.sha AS head_sha,
    base.ref AS base_ref,
    base.sha AS base_sha,
    author_association,
    draft,
    auto_merge.merge_method AS auto_merge_method
FROM ${source}.repos_pulls
WHERE owner = '${owner}' AND repo = '${repo}'
WITH NO DATA;

-- loop: pages
MERGE INTO ${target}.pulls t
USING (
    SELECT *
    FROM (
        SELECT
            owner,
            repo,
            id,
            node_id,
            url,
            html_url,
            number,
            state,
            locked,
            title,
            user.id AS user_id,
            user.login AS user_login,
            body,
            transform(labels, label -> label.name) AS label_names,
            milestone.id AS milestone_id,
            milestone.title AS milestone_title,
            active_lock_reason,
            created_at,
            updated_at,
            closed_at,
            merged_at,
            merge_commit_sha,
            assignee.id AS assignee_id,
            assignee.login AS assignee_login,
            transform(assignees, assignee -> assignee.login) AS assignee_logins,
            transform(requested_reviewers, reviewer -> reviewer.login) AS requested_reviewer_logins,
            head.ref AS head_ref,
            head.sha AS head_sha,
            base.ref AS base_ref,
            base.sha AS base_sha,
            author_association,
            draft,
            auto_merge.merge_method AS auto_merge_method,
            row_number() OVER (PARTITION BY id ORDER BY updated_at DESC) AS row_num
        FROM ${source}.repos_pulls
        WHERE owner = '${owner}' AND repo = '${repo}' AND state = 'all' AND sort = 'updated' AND direction = 'desc' AND per_page = 100 AND page = ${page}
    )
    WHERE row_num = 1
) s
ON t.id = s.id
WHEN MATCHED AND s.updated_at > t.updated_at THEN UPDATE SET
    owner = s.owner,
    repo = s.repo,
    id = s.id,
    node_id = s.node_id,
    url = s.url,
    html_url = s.html_url,
    number = s.number,
    state = s.state,
    locked = s.locked,
    title = s.title,
    user_id = s.user_id,
    user_login = s.user_login,
    body = s.body,
    label_names = s.label_names,
    milestone_id = s.milestone_id,
    milestone_title = s.milestone_title,
    active_lock_reason = s.active_lock_reason,
    created_at = s.created_at,
    updated_at = s.updated_at,
    closed_at = s.closed_at,
    merged_at = s.merged_at,
    merge_commit_sha = s.merge_commit_sha,
    assignee_id = s.assignee_id,
    assignee_login = s.assignee_login,
    assignee_logins = s.assignee_logins,
    requested_reviewer_logins = s.requested_reviewer_logins,
    head_ref = s.head_ref,
    head_sha = s.head_sha,
    base_ref = s.base_ref,
    base_sha = s.base_sha,
    author_association = s.author_association,
    draft = s.draft,
    auto_merge_method = s.auto_merge_method
WHEN NOT MATCHED THEN INSERT (
    owner,
    repo,
    id,
    node_id,
    url,
    html_url,
    number,
    state,
    locked,
    title,
    user_id,
    user_login,
    body,
    label_names,
    milestone_id,
    milestone_title,
    active_lock_reason,
    created_at,
    updated_at,
    closed_at,
    merged_at,
    merge_commit_sha,
    assignee_id,
    assignee_login,
    assignee_logins,
    requested_reviewer_logins,
    head_ref,
    head_sha,
    base_ref,
    base_sha,
    author_association,
    draft,
    auto_merge_method
)
VALUES (
    s.owner,
    s.repo,
    s.id,
    s.node_id,
    s.url,
    s.html_url,
    s.number,
    s.state,
    s.locked,
    s.title,
    s.user_id,
    s.user_login,
    s.body,
    s.label_names,
    s.milestone_id,
    s.milestone_title,
    s.active_lock_reason,
    s.created_at,
    s.updated_at,
    s.closed_at,
    s.merged_at,
    s.merge_commit_sha,
    s.assignee_id,
    s.assignee_login,
    s.assignee_logins,
    s.requested_reviewer_logins,
    s.head_ref,
    s.head_sha,
    s.base_ref,
    s.base_sha,
    s.author_association,
    s.draft,
    s.auto_merge_method
);
