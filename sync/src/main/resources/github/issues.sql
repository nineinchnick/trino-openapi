-- Issues and pull requests, read using the issues endpoint, which can return only the ones updated since the cursor.
-- The cursor is a scalar subquery, which Trino passes to the connector as a dynamic filter,
-- so it's sent as the since parameter. It must have the same type as the column, so it's cast to timestamp(3).
CREATE SCHEMA IF NOT EXISTS ${target};

CREATE TABLE IF NOT EXISTS ${target}.issues AS
SELECT
    owner,
    repo,
    id,
    node_id,
    url,
    html_url,
    number,
    state,
    state_reason,
    title,
    body,
    user.id AS user_id,
    user.login AS user_login,
    labels,
    assignee.id AS assignee_id,
    assignee.login AS assignee_login,
    transform(assignees, assignee -> assignee.login) AS assignee_logins,
    milestone.id AS milestone_id,
    milestone.title AS milestone_title,
    locked,
    active_lock_reason,
    comments,
    pull_request.html_url AS pull_request_url,
    pull_request.merged_at AS pull_request_merged_at,
    closed_at,
    created_at,
    updated_at,
    closed_by.id AS closed_by_id,
    closed_by.login AS closed_by_login,
    author_association,
    draft,
    reactions.total_count AS reactions_total_count,
    type.name AS type_name
FROM ${source}.repos_issues
WHERE owner = '${owner}' AND repo = '${repo}'
WITH NO DATA;

MERGE INTO ${target}.issues t
USING (
    SELECT *
    FROM (
        SELECT
            owner,
            repo,
            id,
            node_id,
            url,
            html_url,
            number,
            state,
            state_reason,
            title,
            body,
            user.id AS user_id,
            user.login AS user_login,
            labels,
            assignee.id AS assignee_id,
            assignee.login AS assignee_login,
            transform(assignees, assignee -> assignee.login) AS assignee_logins,
            milestone.id AS milestone_id,
            milestone.title AS milestone_title,
            locked,
            active_lock_reason,
            comments,
            pull_request.html_url AS pull_request_url,
            pull_request.merged_at AS pull_request_merged_at,
            closed_at,
            created_at,
            updated_at,
            closed_by.id AS closed_by_id,
            closed_by.login AS closed_by_login,
            author_association,
            draft,
            reactions.total_count AS reactions_total_count,
            type.name AS type_name,
            row_number() OVER (PARTITION BY id ORDER BY updated_at DESC) AS row_num
        FROM ${source}.repos_issues
        WHERE owner = '${owner}' AND repo = '${repo}' AND state = 'all' AND per_page = 100
            AND updated_at >= (SELECT CAST(coalesce(max(updated_at), TIMESTAMP '2000-01-01') AS timestamp(3)) FROM ${target}.issues WHERE owner = '${owner}' AND repo = '${repo}')
    )
    WHERE row_num = 1
) s
ON t.id = s.id
WHEN MATCHED AND s.updated_at > t.updated_at THEN UPDATE SET
    owner = s.owner,
    repo = s.repo,
    id = s.id,
    node_id = s.node_id,
    url = s.url,
    html_url = s.html_url,
    number = s.number,
    state = s.state,
    state_reason = s.state_reason,
    title = s.title,
    body = s.body,
    user_id = s.user_id,
    user_login = s.user_login,
    labels = s.labels,
    assignee_id = s.assignee_id,
    assignee_login = s.assignee_login,
    assignee_logins = s.assignee_logins,
    milestone_id = s.milestone_id,
    milestone_title = s.milestone_title,
    locked = s.locked,
    active_lock_reason = s.active_lock_reason,
    comments = s.comments,
    pull_request_url = s.pull_request_url,
    pull_request_merged_at = s.pull_request_merged_at,
    closed_at = s.closed_at,
    created_at = s.created_at,
    updated_at = s.updated_at,
    closed_by_id = s.closed_by_id,
    closed_by_login = s.closed_by_login,
    author_association = s.author_association,
    draft = s.draft,
    reactions_total_count = s.reactions_total_count,
    type_name = s.type_name
WHEN NOT MATCHED THEN INSERT (
    owner,
    repo,
    id,
    node_id,
    url,
    html_url,
    number,
    state,
    state_reason,
    title,
    body,
    user_id,
    user_login,
    labels,
    assignee_id,
    assignee_login,
    assignee_logins,
    milestone_id,
    milestone_title,
    locked,
    active_lock_reason,
    comments,
    pull_request_url,
    pull_request_merged_at,
    closed_at,
    created_at,
    updated_at,
    closed_by_id,
    closed_by_login,
    author_association,
    draft,
    reactions_total_count,
    type_name
)
VALUES (
    s.owner,
    s.repo,
    s.id,
    s.node_id,
    s.url,
    s.html_url,
    s.number,
    s.state,
    s.state_reason,
    s.title,
    s.body,
    s.user_id,
    s.user_login,
    s.labels,
    s.assignee_id,
    s.assignee_login,
    s.assignee_logins,
    s.milestone_id,
    s.milestone_title,
    s.locked,
    s.active_lock_reason,
    s.comments,
    s.pull_request_url,
    s.pull_request_merged_at,
    s.closed_at,
    s.created_at,
    s.updated_at,
    s.closed_by_id,
    s.closed_by_login,
    s.author_association,
    s.draft,
    s.reactions_total_count,
    s.type_name
);
