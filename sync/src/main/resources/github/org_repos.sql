-- Repositories of the organization set as the owner, including private ones the token can read,
-- which the repos step doesn't return. Saved in the same table as the repos step. Not run by default,
-- because the endpoint fails for owners that are users.
CREATE SCHEMA IF NOT EXISTS ${target};

CREATE TABLE IF NOT EXISTS ${target}.repos AS
SELECT
    CAST('${owner}' AS varchar) AS owner,
    id,
    node_id,
    name,
    full_name,
    owner.id AS owner_id,
    owner.login AS owner_login,
    private,
    html_url,
    description,
    fork,
    url,
    homepage,
    language,
    forks_count,
    stargazers_count,
    watchers_count,
    size,
    default_branch,
    open_issues_count,
    is_template,
    topics,
    has_issues,
    has_projects,
    has_wiki,
    has_pages,
    has_downloads,
    has_discussions,
    archived,
    disabled,
    visibility,
    license.spdx_id AS license_spdx_id,
    pushed_at,
    created_at,
    updated_at
FROM ${source}.orgs_repos
WHERE org = '${owner}'
WITH NO DATA;

-- loop: pages
MERGE INTO ${target}.repos t
USING (
    SELECT *
    FROM (
        SELECT
            CAST('${owner}' AS varchar) AS owner,
            id,
            node_id,
            name,
            full_name,
            owner.id AS owner_id,
            owner.login AS owner_login,
            private,
            html_url,
            description,
            fork,
            url,
            homepage,
            language,
            forks_count,
            stargazers_count,
            watchers_count,
            size,
            default_branch,
            open_issues_count,
            is_template,
            topics,
            has_issues,
            has_projects,
            has_wiki,
            has_pages,
            has_downloads,
            has_discussions,
            archived,
            disabled,
            visibility,
            license.spdx_id AS license_spdx_id,
            pushed_at,
            created_at,
            updated_at,
            row_number() OVER (PARTITION BY id ORDER BY updated_at DESC) AS row_num
        FROM ${source}.orgs_repos
        WHERE org = '${owner}' AND type = 'all' AND sort = 'updated' AND direction = 'desc' AND per_page = 100 AND page = ${page}
    )
    WHERE row_num = 1
) s
ON t.id = s.id
WHEN MATCHED AND s.updated_at > t.updated_at THEN UPDATE SET
    owner = s.owner,
    id = s.id,
    node_id = s.node_id,
    name = s.name,
    full_name = s.full_name,
    owner_id = s.owner_id,
    owner_login = s.owner_login,
    private = s.private,
    html_url = s.html_url,
    description = s.description,
    fork = s.fork,
    url = s.url,
    homepage = s.homepage,
    language = s.language,
    forks_count = s.forks_count,
    stargazers_count = s.stargazers_count,
    watchers_count = s.watchers_count,
    size = s.size,
    default_branch = s.default_branch,
    open_issues_count = s.open_issues_count,
    is_template = s.is_template,
    topics = s.topics,
    has_issues = s.has_issues,
    has_projects = s.has_projects,
    has_wiki = s.has_wiki,
    has_pages = s.has_pages,
    has_downloads = s.has_downloads,
    has_discussions = s.has_discussions,
    archived = s.archived,
    disabled = s.disabled,
    visibility = s.visibility,
    license_spdx_id = s.license_spdx_id,
    pushed_at = s.pushed_at,
    created_at = s.created_at,
    updated_at = s.updated_at
WHEN NOT MATCHED THEN INSERT (
    owner,
    id,
    node_id,
    name,
    full_name,
    owner_id,
    owner_login,
    private,
    html_url,
    description,
    fork,
    url,
    homepage,
    language,
    forks_count,
    stargazers_count,
    watchers_count,
    size,
    default_branch,
    open_issues_count,
    is_template,
    topics,
    has_issues,
    has_projects,
    has_wiki,
    has_pages,
    has_downloads,
    has_discussions,
    archived,
    disabled,
    visibility,
    license_spdx_id,
    pushed_at,
    created_at,
    updated_at
)
VALUES (
    s.owner,
    s.id,
    s.node_id,
    s.name,
    s.full_name,
    s.owner_id,
    s.owner_login,
    s.private,
    s.html_url,
    s.description,
    s.fork,
    s.url,
    s.homepage,
    s.language,
    s.forks_count,
    s.stargazers_count,
    s.watchers_count,
    s.size,
    s.default_branch,
    s.open_issues_count,
    s.is_template,
    s.topics,
    s.has_issues,
    s.has_projects,
    s.has_wiki,
    s.has_pages,
    s.has_downloads,
    s.has_discussions,
    s.archived,
    s.disabled,
    s.visibility,
    s.license_spdx_id,
    s.pushed_at,
    s.created_at,
    s.updated_at
);
