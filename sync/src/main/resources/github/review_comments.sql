-- Review comments of all pull requests.
CREATE SCHEMA IF NOT EXISTS ${target};

CREATE TABLE IF NOT EXISTS ${target}.review_comments AS
SELECT
    owner,
    repo,
    id,
    node_id,
    url,
    html_url,
    pull_request_review_id,
    diff_hunk,
    path,
    position,
    original_position,
    commit_id,
    original_commit_id,
    in_reply_to_id,
    user.id AS user_id,
    user.login AS user_login,
    body,
    created_at,
    updated_at,
    pull_request_url,
    CAST(regexp_extract(pull_request_url, '/pulls/(\d+)$', 1) AS bigint) AS pull_number,
    author_association,
    start_line,
    original_start_line,
    start_side,
    line,
    original_line,
    side,
    subject_type,
    reactions.total_count AS reactions_total_count
FROM ${source}.repos_owner_repo_pulls_comments_comment_id
WHERE owner = '${owner}' AND repo = '${repo}'
WITH NO DATA;

MERGE INTO ${target}.review_comments t
USING (
    SELECT *
    FROM (
        SELECT
            owner,
            repo,
            id,
            node_id,
            url,
            html_url,
            pull_request_review_id,
            diff_hunk,
            path,
            position,
            original_position,
            commit_id,
            original_commit_id,
            in_reply_to_id,
            user.id AS user_id,
            user.login AS user_login,
            body,
            created_at,
            updated_at,
            pull_request_url,
            CAST(regexp_extract(pull_request_url, '/pulls/(\d+)$', 1) AS bigint) AS pull_number,
            author_association,
            start_line,
            original_start_line,
            start_side,
            line,
            original_line,
            side,
            subject_type,
            reactions.total_count AS reactions_total_count,
            row_number() OVER (PARTITION BY id ORDER BY updated_at DESC) AS row_num
        FROM ${source}.repos_owner_repo_pulls_comments_comment_id
        WHERE owner = '${owner}' AND repo = '${repo}' AND per_page = 100
            AND updated_at >= (SELECT CAST(coalesce(max(updated_at), TIMESTAMP '2000-01-01') AS timestamp(3)) FROM ${target}.review_comments WHERE owner = '${owner}' AND repo = '${repo}')
    )
    WHERE row_num = 1
) s
ON t.id = s.id
WHEN MATCHED AND s.updated_at > t.updated_at THEN UPDATE SET
    owner = s.owner,
    repo = s.repo,
    id = s.id,
    node_id = s.node_id,
    url = s.url,
    html_url = s.html_url,
    pull_request_review_id = s.pull_request_review_id,
    diff_hunk = s.diff_hunk,
    path = s.path,
    position = s.position,
    original_position = s.original_position,
    commit_id = s.commit_id,
    original_commit_id = s.original_commit_id,
    in_reply_to_id = s.in_reply_to_id,
    user_id = s.user_id,
    user_login = s.user_login,
    body = s.body,
    created_at = s.created_at,
    updated_at = s.updated_at,
    pull_request_url = s.pull_request_url,
    pull_number = s.pull_number,
    author_association = s.author_association,
    start_line = s.start_line,
    original_start_line = s.original_start_line,
    start_side = s.start_side,
    line = s.line,
    original_line = s.original_line,
    side = s.side,
    subject_type = s.subject_type,
    reactions_total_count = s.reactions_total_count
WHEN NOT MATCHED THEN INSERT (
    owner,
    repo,
    id,
    node_id,
    url,
    html_url,
    pull_request_review_id,
    diff_hunk,
    path,
    position,
    original_position,
    commit_id,
    original_commit_id,
    in_reply_to_id,
    user_id,
    user_login,
    body,
    created_at,
    updated_at,
    pull_request_url,
    pull_number,
    author_association,
    start_line,
    original_start_line,
    start_side,
    line,
    original_line,
    side,
    subject_type,
    reactions_total_count
)
VALUES (
    s.owner,
    s.repo,
    s.id,
    s.node_id,
    s.url,
    s.html_url,
    s.pull_request_review_id,
    s.diff_hunk,
    s.path,
    s.position,
    s.original_position,
    s.commit_id,
    s.original_commit_id,
    s.in_reply_to_id,
    s.user_id,
    s.user_login,
    s.body,
    s.created_at,
    s.updated_at,
    s.pull_request_url,
    s.pull_number,
    s.author_association,
    s.start_line,
    s.original_start_line,
    s.start_side,
    s.line,
    s.original_line,
    s.side,
    s.subject_type,
    s.reactions_total_count
);
